import {PGlite} from '@electric-sql/pglite';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const A='aaaaaaaa-aaaa-4aaa-aaaa-aaaaaaaaaaaa',B='bbbbbbbb-bbbb-4bbb-bbbb-bbbbbbbbbbbb';
const db=new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
grant usage on schema auth to authenticated, anon; grant execute on function auth.uid() to authenticated, anon;
insert into auth.users values('${A}'),('${B}');`);
await db.exec(fs.readFileSync('supabase/migrations/20261118090000_client_error_reports.sql','utf8').replace("notify pgrst, 'reload schema';",''));
const as=async user=>db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub','${user}',false);`);
const call=(...a)=>db.query('select public.clt_report_client_error($1,$2,$3,$4) ok',a).then(r=>r.rows[0].ok);
await as(A);
assert.equal(await call('windows','2.1.24','WINDOW_ERROR','TypeError: x'),true);
for(const args of [['ios','2.1.24','S','m'],['windows','abc','S','m'],['windows','2.1.24','',' '],['android','2.1.16','S','']])assert.equal(await call(...args),false,args.join(','));
let accepted=0;for(let i=0;i<25;i++)if(await call('android','2.1.16','S','m'+i))accepted++;
assert.equal(accepted,19,'20 reports per account per hour');
await assert.rejects(db.query('select * from public.clt_client_errors'),/permission denied/);
await assert.rejects(db.query(`insert into public.clt_client_errors(user_id,platform,app_version,stage,message) values('${B}','windows','1.0','S','m')`),/permission denied/);
await as(B);assert.equal(await call('windows','2.1.24','S','x'.repeat(5000)),true,'other accounts keep their own limit');
await db.exec(`reset role; set role anon; select set_config('request.jwt.claim.sub','',false);`);
await assert.rejects(call('windows','2.1.24','S','m'),/permission denied/);
await db.exec('reset role');
const rows=(await db.query('select user_id,char_length(message) n from public.clt_client_errors order by id')).rows;
assert.equal(rows.length,21);assert.equal(rows.at(-1).n,900);
await db.exec(`update public.clt_client_errors set created_at=now()-interval '31 days' where user_id='${A}'`);
await as(B);await call('windows','2.1.24','S','retention');await db.exec('reset role');
assert.equal((await db.query(`select count(*)::int n from public.clt_client_errors where user_id='${A}'`)).rows[0].n,0,'reports older than 30 days are removed');
console.log('Client error reports: validation, per-account hourly limit, no reads, no anonymous calls, truncation and 30-day retention passed');
